import { navigate as goTo, openCardio } from './navigation';
import { expect, test } from '@playwright/test';

test('reviews and applies an offline prototype routine, then controls automatic and manual recalibration', async ({ page, context }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await page.goto('/');
  await page.getByRole('navigation', { name: 'Mission sections' }).getByRole('link', { name: 'Onboarding', exact: true }).click();
  await expect(page).toHaveTitle('Onboarding — A.R.E.S.');
  const wizard = page.getByRole('region', { name: 'Mission Onboarding — Set Up Your Profile', exact: true });
  await expect(wizard.getByLabel('Onboarding progress', { exact: true })).toHaveText('Step 1 of 3');
  await wizard.getByLabel('Onboarding astronaut name', { exact: true }).fill('Commander M6');
  await wizard.getByLabel('Onboarding Height (cm)', { exact: true }).fill('180');
  await wizard.getByLabel('Onboarding Body weight (kg)', { exact: true }).fill('81');
  await expect(wizard.getByLabel('Calculated BMI', { exact: true })).toHaveText('25 kg/m²');
  await wizard.getByRole('button', { name: 'Next step', exact: true }).focus();
  await page.keyboard.press('Enter');
  await wizard.getByLabel('Onboarding Squat Earth baseline (kg)', { exact: true }).fill('100');
  await wizard.getByLabel('Onboarding injury or physical limitation', { exact: true }).selectOption('KNEE_SENSITIVITY');
  await wizard.getByLabel('Onboarding limitation notes (optional)', { exact: true }).fill('Reported knee sensitivity');
  await wizard.getByRole('button', { name: 'Next step', exact: true }).click();
  await wizard.getByLabel('Onboarding mission type', { exact: true }).selectOption('LUNAR_ARTEMIS_30D');
  await wizard.getByLabel('Onboarding gravity environment', { exact: true }).selectOption('MOON_016G');
  await wizard.getByRole('button', { name: 'Generate My Routine', exact: true }).click();
  const preview = wizard.getByRole('region', { name: 'Routine preview', exact: true });
  await expect(preview).toBeVisible();
  await expect(preview.getByRole('listitem')).toHaveCount(7);
  await expect(preview).toContainText('Load moderated for knee sensitivity');
  await expect(page.getByLabel('Body weight (kg)', { exact: true })).toHaveValue('78');
  await wizard.getByRole('button', { name: 'Confirm & Apply Routine', exact: true }).click();
  await expect(wizard.getByLabel('Onboarding confirmation', { exact: true })).toHaveText('Profile and routine confirmed and applied.');
  await expect(page.getByLabel('Body weight (kg)', { exact: true })).toHaveValue('81');
  const schedule = page.getByRole('list', { name: 'Personalized daily schedule', exact: true });
  await expect(page.getByLabel('Personalized routine label', { exact: true })).toHaveText('Personalized for you — Adapted to your progress');
  await goTo(page, 'Settings');
  const auto = page.getByRole('checkbox', { name: 'Auto-adjust routine based on progress', exact: true });
  await auto.uncheck();
  await goTo(page, 'Dashboard');
  const frozen = await schedule.innerText();
  await openCardio(page);
  await page.getByLabel('Cardio distance (km)', { exact: true }).fill('7');
  await page.getByRole('button', { name: 'Log cardio session', exact: true }).click();
  await goTo(page, 'Dashboard');
  await expect(schedule).toHaveText(frozen, { useInnerText: true });
  await goTo(page, 'Settings');
  await page.getByRole('button', { name: 'Recalibrate Routine', exact: true }).click();
  await expect(page.getByLabel('Routine update notification', { exact: true })).toHaveText('Your routine has been updated based on your recent progress.');
  await goTo(page, 'Dashboard');
  await expect(schedule).toContainText('6 km');
  await goTo(page, 'Settings');
  await auto.check();
  await openCardio(page);
  await page.getByLabel('Cardio distance (km)', { exact: true }).fill('8');
  await page.getByRole('button', { name: 'Log cardio session', exact: true }).click();
  await goTo(page, 'Dashboard');
  await expect(schedule).toContainText('6.8 km');
  await page.reload();
  await expect(page.getByLabel('Astronaut name', { exact: true })).toHaveValue('Commander M6');
  await goTo(page, 'Settings');
  await expect(page.getByRole('checkbox', { name: 'Auto-adjust routine based on progress', exact: true })).toBeChecked();
  await goTo(page, 'Dashboard');
  await expect(page.getByRole('list', { name: 'Personalized daily schedule', exact: true })).toContainText('6.8 km');
  expect(errors).toEqual([]);
});
