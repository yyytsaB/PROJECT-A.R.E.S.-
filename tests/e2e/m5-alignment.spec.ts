import { navigate } from './navigation';
import { expect, test } from '@playwright/test';

test('aligns the six sections through an accessible offline mission workflow', async ({ page, context }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  await page.goto('/');
  await expect(page).toHaveTitle('Dashboard — ARES');
  await page.keyboard.press('Tab');
  await expect(page.getByRole('link', { name: 'Skip to main content', exact: true })).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('main')).toBeFocused();
  const navigation = page.getByRole('navigation', { name: 'Mission sections' });
  await navigation.getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(page).toHaveTitle('Settings — ARES');
  await navigate(page, 'Profile');
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('0');
  await expect(page.getByText('Body weight must be greater than 0 kg.', { exact: true })).toBeVisible();
  await page.getByLabel('Body weight (kg)', { exact: true }).fill('82');
  await page.getByRole('button', { name: 'Save / Apply', exact: true }).click();
  await expect(page.getByLabel('Profile confirmation', { exact: true })).toHaveText('Profile saved.');
  await navigate(page, 'Settings');
  await page.getByRole('button', { name: 'Clear Local Data', exact: true }).click();
  const warning = page.getByRole('dialog', { name: 'Clear all local mission data?' });
  await expect(warning).toBeVisible();
  await warning.getByRole('button', { name: 'Cancel clear', exact: true }).click();
  await expect(page.getByLabel('Saved session count', { exact: true })).toHaveText('60');
  await page.getByRole('button', { name: 'Clear Local Data', exact: true }).click();
  await warning.getByRole('button', { name: 'Confirm clear', exact: true }).click();
  await expect(page.getByLabel('Saved session count', { exact: true })).toHaveText('0');
  await navigation.getByRole('link', { name: 'Dashboard', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Mark Squat complete', exact: true }).check();
  await page.getByRole('button', { name: "INITIATE TODAY'S SESSION", exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Exercise', exact: true })).toHaveValue('DEADLIFT');
  await page.getByRole('button', { name: 'Simulate Good Rep', exact: true }).click();
  await expect(page.getByLabel('Completed reps', { exact: true })).toHaveText('1');
  await expect(page.getByLabel('Form feedback', { exact: true })).toHaveText('Spine aligned');
  await expect(page.getByLabel('Workout duration', { exact: true })).not.toHaveText('00:00');
  await page.getByRole('button', { name: 'End session', exact: true }).click();
  await navigate(page, 'Dashboard');
  await expect(page.getByRole('checkbox', { name: 'Mark Deadlift complete', exact: true })).toBeChecked();
  await navigation.getByRole('link', { name: 'Logs', exact: true }).click();
  await expect(page).toHaveTitle('Logs — ARES');
  await page.getByLabel('Workout date range', { exact: true }).selectOption('LAST_7_DAYS');
  await expect(page.getByLabel('History pagination', { exact: true })).toHaveText('Page 1 of 1');
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Session details' })).toContainText('GREEN');
  await navigation.getByRole('link', { name: 'Analytics', exact: true }).click();
  await page.getByLabel('Telemetry date window', { exact: true }).selectOption('7');
  await expect(page.getByRole('table', { name: 'Medical telemetry', exact: true }).locator('tbody tr')).toHaveCount(7);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export Flight Surgeon JSON', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('ares-flight-surgeon.json');
  await expect(page.getByLabel('Export confirmation', { exact: true })).toHaveText('Health telemetry report exported.');
  await page.evaluate(() => { window.print = () => {}; });
  await page.getByRole('button', { name: 'Print / Save as PDF', exact: true }).click();
  await expect(page.getByLabel('Export confirmation', { exact: true })).toContainText('Print dialog opened.');
  await navigation.getByRole('link', { name: 'Journey', exact: true }).click();
  await page.getByRole('button', { name: 'View all badges', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Mission badges', exact: true }).getByRole('listitem')).toHaveCount(3);
  await page.reload();
  await navigate(page, 'Dashboard');
  await expect(page.getByRole('checkbox', { name: 'Mark Squat complete', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Mark Deadlift complete', exact: true })).toBeChecked();
  await page.goto('/#history-heading');
  await expect(page).toHaveTitle('Logs — ARES');
  await page.getByRole('navigation', { name: 'Mission sections' }).getByRole('link', { name: 'Settings', exact: true }).click();
  await expect(page).toHaveTitle('Settings — ARES');
  await page.goBack();
  await expect(page).toHaveTitle('Logs — ARES');
  await page.goForward();
  await expect(page).toHaveTitle('Settings — ARES');
  await page.goto('/');
  await page.getByRole('navigation', { name: 'Mission sections' }).getByRole('link', { name: 'Settings', exact: true }).click();
  await page.goBack();
  await expect(page).toHaveTitle('Dashboard — ARES');
  expect(errors).toEqual([]);
});
